/**
 * Retorna o Master Exercise correspondente a um ID ou nome aproximado/aliases.
 */
export function getMasterExerciseById(id: string): MasterExercise | undefined {
  return MASTER_EXERCISES.find((ex) => ex.id === id);
}

export function getMasterExerciseByName(name: string): MasterExercise | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  
  // 1. Exact or ID match
  const exact = MASTER_EXERCISES.find(
    (ex) => ex.id.toLowerCase() === clean || ex.name.trim().toLowerCase() === clean
  );
  if (exact) return exact;

  // 2. Alias match
  const byAlias = MASTER_EXERCISES.find(
    (ex) => ex.aliases && ex.aliases.some((a) => a.trim().toLowerCase() === clean || clean.includes(a.trim().toLowerCase()))
  );
  if (byAlias) return byAlias;

  // 3. Substring match
  return MASTER_EXERCISES.find((ex) => {
    const exClean = ex.name.trim().toLowerCase();
    return exClean.includes(clean) || clean.includes(exClean);
  });
}
